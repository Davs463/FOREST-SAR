// Post-build step for static hosting (GoDaddy / Apache). Operates on dist/ only — never on public/.
//  1. Keeps only the snapshots the site actually loads (manifest + index comparisons); excluded or
//     superseded snapshots stay in public/data (scientific record) but are not shipped.
//  2. Fails if dist contains credentials, raw products, caches or logs.
//  3. Writes dist/.htaccess (MIME types, caching, no directory listing).
// Usage: npm run build:publish
import { existsSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';
const fail = (msg) => { console.error(`prepare-dist: ${msg}`); process.exit(1); };
if (!existsSync(join(DIST, 'index.html'))) fail('dist/index.html missing — run `npm run build` first.');

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));
const dataDir = join(DIST, 'data');
const manifest = readJson(join(dataDir, 'manifest.json'));
const referenced = new Set();
// "snapshots/<id>/file" → "<id>"; "snapshots/index.json" is a file, not a snapshot.
const snapshotOf = (p) => (typeof p === 'string' && /^snapshots\/[^/]+\//.test(p) ? p.split('/')[1] : null);
for (const value of Object.values(manifest)) { const id = snapshotOf(value); if (id) referenced.add(id); }
if (manifest.snapshot_id) referenced.add(manifest.snapshot_id);
const indexPath = manifest.index_path ? join(dataDir, manifest.index_path) : null;
if (indexPath && existsSync(indexPath)) {
  for (const c of readJson(indexPath).comparisons ?? []) if (c.snapshot_id) referenced.add(c.snapshot_id);
}
if (referenced.size === 0) fail('no referenced snapshots found in manifest/index.');

const snapDir = join(dataDir, 'snapshots');
const pruned = [];
for (const name of readdirSync(snapDir)) {
  const full = join(snapDir, name);
  if (statSync(full).isDirectory() && !referenced.has(name)) { rmSync(full, { recursive: true, force: true }); pruned.push(name); }
}
for (const id of referenced) if (!existsSync(join(snapDir, id))) fail(`referenced snapshot ${id} missing from dist.`);

// Forbidden content in a public bundle.
const FORBIDDEN_NAME = /(^\.env|^\.?_?netrc$|\.h5$|\.hdf5$|\.nc$|\.tif$|\.tiff$|\.log$|\.pem$|\.key$|\.py$|\.map$)/i;
const SECRET_TEXT = /(EARTHDATA_TOKEN\s*[=:]|Authorization:\s*Bearer|BEGIN (RSA |EC )?PRIVATE KEY|eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}\.)/;
const LOCAL_PATH = /[A-Za-z]:\\\\Users\\\\|\/Users\/[^/"]+\/|OneDrive[\\/]/;
const TEXT_EXT = /\.(html|js|css|json|geojson|txt|svg|md)$/i;
let bytes = 0; let files = 0; const problems = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) { walk(full); continue; }
    files += 1; bytes += st.size;
    const rel = relative(DIST, full).split(sep).join('/');
    if (FORBIDDEN_NAME.test(name)) problems.push(`forbidden file: ${rel}`);
    if (TEXT_EXT.test(name)) {
      const text = readFileSync(full, 'utf8');
      if (SECRET_TEXT.test(text)) problems.push(`possible credential in ${rel}`);
      if (LOCAL_PATH.test(text)) problems.push(`local machine path in ${rel}`);
    }
  }
};
walk(DIST);
if (problems.length) fail(`\n  ${problems.join('\n  ')}`);

writeFileSync(join(DIST, '.htaccess'), `# Generated by scripts/prepare-dist.mjs — static site, hash routing (no rewrites needed).
Options -Indexes
DirectoryIndex index.html
AddType application/geo+json .geojson
AddType application/json .json
AddType image/svg+xml .svg
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json application/geo+json image/svg+xml
</IfModule>
<IfModule mod_headers.c>
  # Hashed bundles never change; data and index.html are revalidated so new snapshots appear.
  <FilesMatch "^assets/.*\\.(js|css)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(json|geojson|html)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
</IfModule>
`);

console.log(`prepare-dist: OK — ${files} files, ${(bytes / 1048576).toFixed(1)} MB`);
console.log(`  snapshots shipped (${referenced.size}): ${[...referenced].join(', ')}`);
console.log(`  snapshots not shipped (${pruned.length}): ${pruned.join(', ') || 'none'}`);
